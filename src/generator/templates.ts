/**
 * Hover-or-focus tooltip meeting WCAG 1.4.13 (Content on Hover or Focus):
 * dismissible via Escape without moving focus, hoverable (moving the
 * pointer from the trigger onto the bubble keeps it open), and persistent
 * (no auto-hide timeout while hovered or focused). The bubble stays in the
 * DOM at all times — visibility is CSS-only — so aria-describedby always
 * resolves to a real element.
 */
