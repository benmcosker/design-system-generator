/**
 * The generator's own published version, so the devDependency it emits into
 * generated systems tracks whatever version is actually generating them
 * instead of a value that goes stale the moment semantic-release bumps it.
 */
function getOwnVersion(): string {
  const here = dirname(fileURLToPath(import.meta.url));
  const pkg = JSON.parse(readFileSync(join(here, '..', '..', 'package.json'), 'utf8')) as {
    version: string;
  };
  return pkg.version;
}

