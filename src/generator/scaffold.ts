/**
 * The source-of-truth token spec, written into the generated repo as
 * tokens.yaml so `dsg check tokens.yaml` can re-validate WCAG AA contrast in
 * the generated system's own CI. The `computed` values are dropped — they're
 * re-derived by resolveTokens() on every check, not part of the spec itself.
 */
export function renderTokenSpecYaml(tokens: ResolvedTokens): string {
  const { computed: _computed, ...spec } = tokens;
  const specOnly: TokenSpec = spec;
  return (
    '# Generated by design-system-generator — the source-of-truth token spec\n' +
    '# for this design system. Run `npm run check` (or `dsg check tokens.yaml`)\n' +
    '# to re-validate WCAG AA contrast after editing colors here.\n' +
    YAML.stringify(specOnly)
  );
}

/**
 * CI workflow for the generated repo: a required, non-overridable WCAG AA
 * contrast gate. No continue-on-error, no skip path — a failing check fails
 * the build.
 */
export function renderContrastWorkflow(): string {
  return `# Generated by design-system-generator.
#
# A failing WCAG AA contrast check is a hard build failure — no
# continue-on-error, no skip path. Pair this with branch protection
# ("Include administrators") so it can't be bypassed; see the README's
# "Enforce the gate (no override)" section for the one-time setup command.
name: Contrast gate

on:
  push:
    branches: [main]
  pull_request:

jobs:
  contrast:
    name: WCAG AA contrast gate
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-node@v4
        with:
          node-version: 22
          cache: npm
      - run: npm ci
      - run: npx dsg check tokens.yaml
`;
}

export function renderGeneratedReadme(tokens: ResolvedTokens, components: ComponentFiles[]): string {
  const list = components.map((c) => `- **${c.name}** — see \`src/${c.name}/${c.name}.docs.md\``).join('\n');
  return `# ${tokens.name}-design-system

A React + TypeScript component library generated from design tokens by
[design-system-generator](https://github.com/benmcosker/design-system-generator).

## Components

${list}

## Accessibility

- Token colors were verified against WCAG AA contrast ratios **before generation** — the generator refuses to emit an inaccessible palette.
- Every component ships with an axe-core test (\`npm test\`).
- Storybook runs with \`@storybook/addon-a11y\` set to fail on violations.
- \`.github/workflows/contrast.yml\` re-runs the same WCAG AA check
  (\`dsg check tokens.yaml\`) on every push and PR — see below to make it
  non-overridable.

## Scripts

| Command | What it does |
| --- | --- |
| \`npm test\` | Runs axe-core accessibility tests for every component (vitest + jsdom) |
| \`npm run check\` | Re-validates \`tokens.yaml\` against WCAG AA contrast |
| \`npm run storybook\` | Auto-generated Storybook docs with the a11y addon |
| \`npm run chromatic\` | Visual regression via Chromatic (set \`CHROMATIC_PROJECT_TOKEN\`) |

## Enforce the gate (no override)

\`.github/workflows/contrast.yml\` makes a failing contrast check a hard CI
failure, but CI alone doesn't stop someone with admin rights from merging a
red PR. Run this once (requires the [\`gh\`](https://cli.github.com/) CLI and
admin on the repo) to make the \`contrast\` check required and
non-bypassable, including for admins:

\`\`\`bash
gh api -X PUT repos/OWNER/REPO/branches/main/protection \\
  -F required_status_checks.strict=true \\
  -F 'required_status_checks.contexts[]=contrast' \\
  -F enforce_admins=true \\
  -F required_pull_request_reviews.required_approving_review_count=0 \\
  -F restrictions=
\`\`\`

Replace \`OWNER/REPO\` with this repository. \`enforce_admins=true\` is the
part that removes the override — without it, repo admins can still merge
past a red check.

## Publishing

The package is set up for semantic versioning: version \`0.0.0-development\`
is replaced at release time. Wire it into CI with
[semantic-release](https://github.com/semantic-release/semantic-release) and
conventional commits.
`;
}
